"""Fit a neuronal action map from the learner's own verified experience.

Recorded controls are used to audit and train, never as a runtime schedule.
The candidate actor is always evaluated in closed loop from the start line.
"""
import argparse
import copy
import json
import pickle
import time
from pathlib import Path
import numpy as np
import torch
from neural_sac import ROOT, BRIDGE, GentleWarmSAC, NodePipe, validate, atomic_json, file_hash

def episodes(buffer):
    capacity = buffer.buffer_size
    order = list(range(buffer.pos, capacity)) + list(range(0, buffer.pos)) if buffer.full else list(range(buffer.pos))
    result = []
    # The last member preserves the genuinely learned prior, not an exploration.
    for env in range(buffer.n_envs - 1):
        rows = []
        started = not buffer.full
        for row in order:
            if started:
                rows.append(row)
            if buffer.dones[row, env]:
                if started and len(rows) >= 10:
                    result.append({'env': env, 'rows': rows, 'reward': float(buffer.rewards[rows, env].sum()), 'length': len(rows)})
                rows = []
                started = True
    return result

def audit_episode(model, pipe, buffer, episode):
    state = pipe.request('reset', mode='practice')
    for row in episode['rows']:
        observed = np.asarray(state['observation'], dtype=np.float32)
        expected = buffer.observations[row, episode['env']]
        if not np.array_equal(observed, expected):
            raise RuntimeError('Recorded neuronal state differs from real independent replay')
        # SB3 stores scaled actions; apply exactly the same public unscaling
        # as the post-warmup rollout before sending them to the simulator.
        action = model.policy.unscale_action(buffer.actions[row, episode['env']])
        state = pipe.request('step', action=action.tolist())
    if not state['terminated'] or state['truncated']:
        raise RuntimeError('Selected completed experience did not terminate naturally')
    return state['info']

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--tag', default='self-experience-first')
    parser.add_argument('--updates', type=int, default=2000)
    args = parser.parse_args()
    if not args.tag.replace('-', '').isalnum() or not 100 <= args.updates <= 10000:
        raise ValueError('Invalid settings')
    source = ROOT / '.impeccable/review/neural-sacl/sac-protected-prior-cuda'
    output = ROOT / '.impeccable/review/neural-sacl' / args.tag
    output.mkdir(parents=True, exist_ok=False)
    report = json.loads((source / 'report.json').read_text(encoding='utf-8'))
    if report['identity']['sourceHashes']['work/neural-rl-bridge.cjs'] != file_hash(BRIDGE):
        raise RuntimeError('Simulator implementation changed')
    if not torch.cuda.is_available():
        raise RuntimeError('Actual CUDA device required')
    torch.set_num_threads(1)
    torch.manual_seed(1409917)
    random = np.random.default_rng(1409917)
    # This exact file was generated by this task's previous verified run.
    # Never accept a user-supplied or downloaded pickle/model through this tool.
    with (source / 'own-replay-buffer.pkl').open('rb') as handle:
        buffer = pickle.load(handle)
    model = GentleWarmSAC.load(source / 'best-own-model.zip', device='cuda')
    pipe = NodePipe()
    try:
        if pipe.metadata != report['identity']['environment']:
            raise RuntimeError('Anatomy/objective/source identity differs')
        corpus = episodes(buffer)
        proposed = sorted(corpus, key=lambda e:e['reward'], reverse=True)[:16] + sorted(corpus, key=lambda e:e['length'], reverse=True)[:16]
        candidates = []
        seen = set()
        for episode in proposed:
            identity = (episode['env'], episode['rows'][0])
            if identity in seen:
                continue
            seen.add(identity)
            physical = audit_episode(model, pipe, buffer, episode)
            candidates.append({**episode, 'physicalReplay':physical})
            print('SELF_EXPERIENCE_REPLAY '+json.dumps({'env':episode['env'],'length':episode['length'],
                                                       'reward':episode['reward'],'physical':physical}), flush=True)
        if not candidates:
            raise RuntimeError('No independently verified complete own episodes')
        selected = max(candidates, key=lambda e:(e['physicalReplay']['laps'],e['physicalReplay']['bestProgress']))
        observations = buffer.observations[selected['rows'], selected['env']].copy()
        actions = buffer.actions[selected['rows'], selected['env']].copy()
        baseline = validate(model, pipe, 'full')
        best = baseline
        best_actor = copy.deepcopy(model.actor.state_dict())
        model.save(output / 'best-own-model.zip')
        optimizer = torch.optim.Adam(model.actor.parameters(), lr=1e-3)
        obs_tensor = torch.as_tensor(observations, device='cuda')
        action_tensor = torch.as_tensor(actions, device='cuda')
        evaluations = []
        started = time.monotonic()
        for update in range(1, args.updates + 1):
            index = torch.as_tensor(random.integers(0, len(observations), size=64), device='cuda')
            predicted = model.actor(obs_tensor[index], deterministic=True)
            loss = (predicted-action_tensor[index]).square().mean()
            if not torch.isfinite(loss):
                raise RuntimeError('Non-finite own-experience regression')
            optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.actor.parameters(), 5)
            optimizer.step()
            if update % 200 == 0:
                full = validate(model, pipe, 'full')
                row = {'update':update,'fitLoss':float(loss.item()),'independentFullValidation':full,
                       'wallSeconds':time.monotonic()-started}
                evaluations.append(row)
                if not full['censored'] and (full['laps']>best['laps'] or full['laps']==best['laps'] and full['bestProgress']>best['bestProgress']):
                    best=full
                    best_actor=copy.deepcopy(model.actor.state_dict())
                    model.save(output / 'best-own-model.zip')
                atomic_json(output / 'progress.json', {'selectedSequenceReplay':selected['physicalReplay'],
                                                       'last':row,'bestStableActor':best})
                print('SELF_EXPERIENCE_FIT '+json.dumps(row), flush=True)
                if best['complete'] and best['laps']==2 and not best['censored']:
                    break
        model.actor.load_state_dict(best_actor)
        verified = validate(model, pipe, 'full')
        keys=['bestProgress','fitness','laps','reason','totalSimulationSeconds']
        if any(verified[k]!=best[k] for k in keys):
            raise RuntimeError('Best actor failed independent full repeat')
        output_report={'format':'male-cns-self-generated-experience-fit-v1','source':str(source.relative_to(ROOT)),
                       'sourceReplaySha256':file_hash(source/'own-replay-buffer.pkl'),
                       'sourceCodeSha256':file_hash(__file__),'environment':pipe.metadata,
                       'gpu':torch.cuda.get_device_name(0),'baseline':baseline,'selectedSequenceReplay':selected,
                       'observedTrainingRows':len(observations),'bestStableActor':best,'independentRepeat':verified,
                       'evaluations':evaluations,
                       'boundary':'Action targets are the learner own actually executed stochastic controls, not an expert, prescribed route or invented example. Recorded sequences are audited only, never runtime schedules. The deployed candidate reads real neuronal observations. Sequence replay, fitting loss and independent complete from-line driving are distinct evidence. Private own model files only; no legacy save/app/release modification.'}
        atomic_json(output/'report.json',output_report)
        print('SELF_EXPERIENCE_DONE '+json.dumps({'baseline':baseline,'sequence':selected['physicalReplay'],
                                                'best':best,'repeat':verified}), flush=True)
    finally:
        pipe.close()

if __name__=='__main__':
    main()
